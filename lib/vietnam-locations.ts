// Generate project key based on location
export function generateProjectKey(provinceCode: string, districtCode: string): string {
  const province = VIETNAM_PROVINCES.find(p => p.code === provinceCode);
  if (!province) return 'PRJ';
  
  const district = province.districts.find(d => d.code === districtCode);
  
  // Create key from province and district codes
  const provincePrefix = provinceCode.toUpperCase().substring(0, 2);
  const districtPrefix = district && district.code !== 'all' 
    ? district.code.toUpperCase().substring(0, 2) 
    : '';
  
  return `${provincePrefix}${districtPrefix}-${Date.now().toString().slice(-4)}`;
}
